/**
 * Reads Sagitta's websites and writes the snapshot shipped with each build.
 *
 *   npx tsx backend/scripts/sync-sagitta-sites.ts
 *
 * A running backend also re-reads the sites daily, so this only sets the starting point.
 */
import fs from "node:fs";
import path from "node:path";
import { crawlSagittaSites } from "../src/assistant/sagitta-sites";

const OUTPUT = path.resolve(__dirname, "../src/assistant/sagitta-sites.data.ts");

(async () => {
  const corpus = await crawlSagittaSites();
  if (corpus.pages < 50) throw new Error(`Only ${corpus.pages} pages were read, so the snapshot wasn't replaced.`);
  fs.writeFileSync(
    OUTPUT,
    `// Generated by backend/scripts/sync-sagitta-sites.ts from Sagitta's live websites. Don't edit by hand.\n\nexport const SAGITTA_SITES_SNAPSHOT = ${JSON.stringify(corpus)};\n`,
    "utf8",
  );
  console.log(`Wrote ${corpus.chunks.length} passages from ${corpus.pages} pages.`, corpus.hosts);
})();
