/**
 * Copies the public record of Sagitta's systems into Selun.
 *
 *   npx tsx backend/scripts/sync-sagitta-directory.ts [path-to-Systems-repo]
 *
 * The source of truth is Systems/src/content/systems.ts, the owner-verified content behind
 * sagitta.systems. Selun deploys separately and can't read that repo at runtime, so this
 * writes a snapshot. Run it again when that content changes. Only the fields below are
 * copied: verification sources, drafts, and archived records are left behind.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const OUTPUT = path.resolve(__dirname, "../src/assistant/sagitta-directory.data.ts");
const source = path.resolve(process.argv[2] ?? path.resolve(__dirname, "../../../../Systems"), "src/content/systems.ts");

type Link = { label: string; href: string };

const EXCLUDED = /sagitta\s*labs|sagittalabs/i;

function httpsOnly(links: Link[] | undefined): Link[] {
  return (links ?? []).filter((link) => link.href.startsWith("https://") && !EXCLUDED.test(`${link.label} ${link.href}`)).map(({ label, href }) => ({ label, href }));
}

(async () => {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const content = (await import(pathToFileURL(source).href)) as any;
  const family = (id: string) => content.getFamily(id)?.name ?? null;
  const name = (slug?: string) => (slug ? content.getSystemName(slug) ?? null : null);

  const systems = content.publicSystems
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    .map((record: any) => ({
      slug: record.slug,
      name: record.name,
      shortName: record.shortName,
      family: family(record.family),
      kind: record.systemKind,
      parent: name(record.parentSystem),
      status: record.status,
      summary: record.summary,
      role: record.ecosystemRole,
      problem: record.problem,
      overview: record.overview,
      availableToday: record.availableToday,
      audience: record.audience,
      url: record.operatingUrl?.startsWith("https://") ? record.operatingUrl : null,
      links: httpsOnly(record.evidence),
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      connections: (record.connections ?? []).map((entry: any) => ({ system: name(entry.slug), reason: entry.reason })),
      lastVerifiedAt: record.verification?.lastVerifiedAt ?? null,
    }));
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const capabilities = content.publicCapabilities.map((record: any) => ({
    slug: record.slug,
    name: record.name,
    summary: record.summary,
    overview: record.overview,
    audience: record.audience,
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    deliveredBy: (record.deliveredBy ?? []).map((slug: string) => name(slug)).filter(Boolean),
    accessPath: record.accessPath ?? null,
    url: record.operatingUrl?.startsWith("https://") ? record.operatingUrl : null,
    lastVerifiedAt: record.verification?.lastVerifiedAt ?? null,
  }));

  const body = [
    "// Generated by backend/scripts/sync-sagitta-directory.ts from Systems/src/content/systems.ts. Don't edit by hand.",
    "",
    `export const SAGITTA_SYSTEMS = ${JSON.stringify(systems, null, 2)} as const;`,
    "",
    `export const SAGITTA_CAPABILITIES = ${JSON.stringify(capabilities, null, 2)} as const;`,
    "",
  ].join("\n");
  fs.writeFileSync(OUTPUT, body, "utf8");
  console.log(`Wrote ${systems.length} systems and ${capabilities.length} capabilities.`);
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  for (const s of systems) console.log(`  ${s.name} | ${s.kind} | ${s.status} | ${s.url} | parent ${s.parent}`);
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  for (const c of capabilities) console.log(`  capability: ${c.name} | ${c.url}`);
})();
